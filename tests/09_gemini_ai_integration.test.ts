import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { checkRateLimit } from '../server/services/geminiService';

describe('LifeGuard QA: 09. Gemini AI Integration & Clinical Guardrails', () => {
  describe('Sliding Window Rate Limiter', () => {
    it('should permit up to 30 requests per minute for an IP address', () => {
      const testIp = '192.168.1.100_' + Date.now();
      for (let i = 0; i < 30; i++) {
        const { allowed, remaining } = checkRateLimit(testIp);
        assert.equal(allowed, true, `Request ${i + 1} should be permitted`);
        assert.equal(remaining, 30 - (i + 1));
      }
    });

    it('should block the 31st request and return remaining: 0', () => {
      const testIp = '192.168.1.101_' + Date.now();
      for (let i = 0; i < 30; i++) {
        checkRateLimit(testIp);
      }
      const request31 = checkRateLimit(testIp);
      assert.equal(request31.allowed, false, '31st request must be blocked');
      assert.equal(request31.remaining, 0);
    });
  });

  describe('Clinical Safety Guardrails & Disclaimers', () => {
    const MANDATORY_GUARDRAIL_RULES = [
      'NEVER PROVIDE A DEFINITIVE MEDICAL DIAGNOSIS',
      'NEVER INDEPENDENTLY PRESCRIBE, ADJUST, OR ALTER MEDICATION DOSAGES',
      'NEVER CLAIM THAT A LAB REPORT PROVES A SPECIFIC DISEASE',
      'URGENT TRIAGE: For severe red-flag symptoms',
      'DO NOT DELAY EMERGENCY CARE',
      'PRESCRIPTION SCANNING: Extract only clearly visible medicine names'
    ];

    it('should enforce non-diagnostic disclaimer in all clinical responses', () => {
      const STANDARD_CLINICAL_DISCLAIMER = 'This analysis is generated by AI for educational and preparation purposes only. It is NOT a clinical diagnosis and does not replace consultation with a qualified medical professional. Always verify medications with your doctor or pharmacist.';

      assert.ok(STANDARD_CLINICAL_DISCLAIMER.includes('NOT a clinical diagnosis'));
      assert.ok(STANDARD_CLINICAL_DISCLAIMER.includes('consultation with a qualified medical professional'));
    });

    it('should mandate triage referral to 108 or 112 for acute red flag symptoms', () => {
      const redFlags = ['chest pain', 'unilateral numbness', 'difficulty breathing', 'anaphylaxis'];
      const triggerTriageNotice = (symptom: string) => {
        if (redFlags.some(rf => symptom.toLowerCase().includes(rf))) {
          return {
            urgency: 'CRITICAL',
            callEmergency: '108',
            notice: '⚠️ RED FLAG SYMPTOM DETECTED: Call 108 ambulance immediately or visit the nearest emergency room. Do not wait for AI analysis.'
          };
        }
        return { urgency: 'ROUTINE', notice: 'Consult your physician for routine advice.' };
      };

      const triageResult = triggerTriageNotice('Patient experiencing severe crushing chest pain and sweating');
      assert.equal(triageResult.urgency, 'CRITICAL');
      assert.equal(triageResult.callEmergency, '108');
      assert.ok(triageResult.notice.includes('108'));
    });
  });

  describe('Uncertainty Scoring for Ambiguous or Handwritten Data', () => {
    it('should mark ambiguous, smudged, or illegible handwriting as UNCERTAIN', () => {
      interface ExtractedMedicineItem {
        name: string;
        dosage: string;
        confidence: 'HIGH' | 'MEDIUM' | 'UNCERTAIN';
        uncertaintyWarning?: string;
      }

      const evaluateExtractionConfidence = (ocrText: string): ExtractedMedicineItem => {
        if (ocrText.includes('?') || ocrText.includes('~') || ocrText.length < 3) {
          return {
            name: ocrText,
            dosage: 'Unclear',
            confidence: 'UNCERTAIN',
            uncertaintyWarning: '[Unclear Handwriting - Verify with Pharmacist before consumption]'
          };
        }
        return {
          name: ocrText,
          dosage: '500mg',
          confidence: 'HIGH'
        };
      };

      const clearMed = evaluateExtractionConfidence('Paracetamol 500mg');
      assert.equal(clearMed.confidence, 'HIGH');
      assert.equal(clearMed.uncertaintyWarning, undefined);

      const smudgedMed = evaluateExtractionConfidence('Metf???~ 5?0');
      assert.equal(smudgedMed.confidence, 'UNCERTAIN');
      assert.ok(smudgedMed.uncertaintyWarning?.includes('Verify with Pharmacist'));
    });
  });

  describe('Offline Heuristic Fallback Detection', () => {
    it('should indicate fallbackRequired: true when Gemini API key is missing', () => {
      const checkAiAvailability = (apiKeyPresent: boolean) => {
        if (!apiKeyPresent) {
          return {
            status: 503,
            error: 'Gemini API is not configured on the server. Falling back to offline clinical heuristics.',
            fallbackRequired: true
          };
        }
        return { status: 200, configured: true };
      };

      const fallbackState = checkAiAvailability(false);
      assert.equal(fallbackState.status, 503);
      assert.equal(fallbackState.fallbackRequired, true);
    });
  });
});
