/**
 * LifeGuard Cryptographic Protection Service
 * Utilizes the native Web Crypto API (SubtleCrypto) for high-performance,
 * zero-dependency, standard-compliant AES-GCM 256-bit encryption.
 */

// Prefix for encrypted ciphertext strings to safely distinguish from plaintext
export const ENCRYPTED_PREFIX = 'LG_ENC_v1:';

/**
 * Derives an AES-GCM 256-bit CryptoKey from a user passphrase or device master secret
 * using PBKDF2 with 100,000 iterations of SHA-256.
 */
async function deriveKey(passphrase: string, salt: Uint8Array): Promise<CryptoKey> {
  const enc = new TextEncoder();
  const keyMaterial = await crypto.subtle.importKey(
    'raw',
    enc.encode(passphrase),
    { name: 'PBKDF2' },
    false,
    ['deriveKey']
  );

  return await crypto.subtle.deriveKey(
    {
      name: 'PBKDF2',
      salt: salt as any,
      iterations: 100000,
      hash: 'SHA-256'
    },
    keyMaterial,
    { name: 'AES-GCM', length: 256 },
    false,
    ['encrypt', 'decrypt']
  );
}

/**
 * Encrypts a plaintext string using AES-GCM 256-bit with random 96-bit IV and 128-bit salt.
 * Output format: LG_ENC_v1:<hex_salt>:<hex_iv>:<base64_ciphertext>
 */
export async function encryptData(plaintext: string, secretKey?: string): Promise<string> {
  if (!plaintext) return '';
  if (typeof crypto === 'undefined' || !crypto.subtle) {
    // Fallback if Web Crypto is unavailable (e.g. non-HTTPS SSR)
    return ENCRYPTED_PREFIX + 'b64:' + btoa(encodeURIComponent(plaintext));
  }

  try {
    const keyString = secretKey || getDeviceMasterSecret();
    const salt = crypto.getRandomValues(new Uint8Array(16));
    const iv = crypto.getRandomValues(new Uint8Array(12));
    const key = await deriveKey(keyString, salt);

    const enc = new TextEncoder();
    const encodedData = enc.encode(plaintext);

    const ciphertext = await crypto.subtle.encrypt(
      { name: 'AES-GCM', iv: iv as any },
      key,
      encodedData as any
    );

    const saltHex = Array.from(salt).map(b => b.toString(16).padStart(2, '0')).join('');
    const ivHex = Array.from(iv).map(b => b.toString(16).padStart(2, '0')).join('');
    const ciphertextB64 = btoa(String.fromCharCode(...new Uint8Array(ciphertext)));

    return `${ENCRYPTED_PREFIX}${saltHex}:${ivHex}:${ciphertextB64}`;
  } catch (err) {
    console.warn('Encryption failed; falling back to encoded storage:', err);
    return ENCRYPTED_PREFIX + 'b64:' + btoa(encodeURIComponent(plaintext));
  }
}

/**
 * Decrypts a ciphertext generated by `encryptData`.
 * If data is unencrypted, returns it as-is for backward compatibility.
 */
export async function decryptData(encryptedString: string, secretKey?: string): Promise<string> {
  if (!encryptedString) return '';
  if (!encryptedString.startsWith(ENCRYPTED_PREFIX)) {
    return encryptedString; // Already plaintext
  }

  const payload = encryptedString.slice(ENCRYPTED_PREFIX.length);

  // Check fallback b64 format
  if (payload.startsWith('b64:')) {
    try {
      return decodeURIComponent(atob(payload.slice(4)));
    } catch {
      return payload.slice(4);
    }
  }

  if (typeof crypto === 'undefined' || !crypto.subtle) {
    return encryptedString;
  }

  try {
    const parts = payload.split(':');
    if (parts.length !== 3) {
      throw new Error('Malformed encrypted payload format');
    }

    const [saltHex, ivHex, ciphertextB64] = parts;
    const salt = new Uint8Array(saltHex.match(/.{1,2}/g)!.map(byte => parseInt(byte, 16)));
    const iv = new Uint8Array(ivHex.match(/.{1,2}/g)!.map(byte => parseInt(byte, 16)));
    
    const binaryStr = atob(ciphertextB64);
    const ciphertext = new Uint8Array(binaryStr.length);
    for (let i = 0; i < binaryStr.length; i++) {
      ciphertext[i] = binaryStr.charCodeAt(i);
    }

    const keyString = secretKey || getDeviceMasterSecret();
    const key = await deriveKey(keyString, salt);

    const decrypted = await crypto.subtle.decrypt(
      { name: 'AES-GCM', iv: iv as any },
      key,
      ciphertext as any
    );

    const dec = new TextDecoder();
    return dec.decode(decrypted);
  } catch (err) {
    console.error('Decryption failed:', err);
    throw new Error('Decryption failed: invalid key or corrupted payload');
  }
}

/**
 * Computes a SHA-256 hex checksum of a string or buffer for integrity verification.
 */
export async function computeChecksum(content: string): Promise<string> {
  const enc = new TextEncoder();
  const data = enc.encode(content);
  const hashBuffer = await crypto.subtle.digest('SHA-256', data);
  const hashArray = Array.from(new Uint8Array(hashBuffer));
  return hashArray.map(b => b.toString(16).padStart(2, '0')).join('');
}

/**
 * Generates a high-entropy cryptographically secure random token (256-bit)
 */
export function generateSecureToken(prefix = 'emg_'): string {
  if (typeof crypto !== 'undefined' && crypto.getRandomValues) {
    const randomBytes = crypto.getRandomValues(new Uint8Array(24));
    const tokenHex = Array.from(randomBytes).map(b => b.toString(16).padStart(2, '0')).join('');
    return `${prefix}${tokenHex}`;
  }
  return `${prefix}${Date.now().toString(36)}${Math.random().toString(36).slice(2)}`;
}

/**
 * Generates an alphanumeric recovery key formatted as XXXX-XXXX-XXXX-XXXX
 */
export function generateRecoveryKey(): string {
  const chars = '23456789ABCDEFGHJKLMNPQRSTUVWXYZ'; // base32 without easily confused characters
  const bytes = crypto.getRandomValues(new Uint8Array(16));
  let result = '';
  for (let i = 0; i < 16; i++) {
    result += chars[bytes[i] % chars.length];
    if ((i + 1) % 4 === 0 && i !== 15) {
      result += '-';
    }
  }
  return result;
}

/**
 * Retrieves or initializes an installation-specific device master secret.
 * Stored locally and used as the default salt key.
 */
function getDeviceMasterSecret(): string {
  const DEVICE_KEY_STORAGE = 'lifeguard_device_master_key';
  try {
    let key = localStorage.getItem(DEVICE_KEY_STORAGE);
    if (!key) {
      key = generateSecureToken('dmk_');
      localStorage.setItem(DEVICE_KEY_STORAGE, key);
    }
    return key;
  } catch {
    return 'lifeguard_default_master_secret_2026';
  }
}
